"""Generate supabase/seed/catalog.sql from packages/catalog/civic_catalog.json and domains/*.yaml.

The catalog JSON is the seed of the `categories` table (plan §4.1); domain packs fill
`domains` and `domain_categories` (plan §4.2). The output is idempotent upserts, so it can
run on every deploy. Categories referenced by a domain but missing from the catalog are
skipped with a warning.

    python scripts/sync_catalog.py            # writes supabase/seed/catalog.sql
    python scripts/sync_catalog.py --check    # fails if the file is out of date (CI)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "packages" / "catalog" / "civic_catalog.json"
DOMAINS = ROOT / "domains"
OUT = ROOT / "supabase" / "seed" / "catalog.sql"

ARRAY_FIELDS = ["context_prompts", "target_prompts", "extra_target_prompts", "resolved_prompts", "confuser_prompts"]
TEXT_FIELDS = ["issue_description", "resolved_description", "vlm_hints"]


def lit(value) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def jlit(value) -> str:
    return lit(json.dumps(value, ensure_ascii=False)) + "::jsonb"


def alit(values) -> str:
    return "array[" + ", ".join(lit(v) for v in values) + "]::text[]" if values else "'{}'::text[]"


def category_sql(cat: dict) -> str:
    cols = {
        "id": lit(cat["id"]),
        "family": lit(cat["domain"]),
        "status": lit(cat.get("status", "active")),
        "display_name": jlit(cat["display_name"]),
        "keywords": jlit(cat["keywords"]),
        "keyword_priority": lit(cat.get("keyword_priority", 0)),
        "photo_verifiability": lit(cat["photo_verifiability"]),
        "default_priority": lit(cat.get("default_priority", "medium")),
        "issue_can_be_global": lit(cat.get("issue_can_be_global", False)),
        **{f: alit(cat.get(f, [])) for f in ARRAY_FIELDS},
        **{f: lit(cat.get(f)) for f in TEXT_FIELDS},
    }
    names = ", ".join(cols)
    updates = ", ".join(f"{c} = excluded.{c}" for c in cols if c not in ("id", "status"))
    snapshot = {k: cat.get(k) for k in ["display_name", "photo_verifiability", *ARRAY_FIELDS, *TEXT_FIELDS, "issue_can_be_global"]}
    return (
        f"insert into categories ({names}) values ({', '.join(cols.values())})\n"
        f"  on conflict (id) do update set {updates};\n"
        f"insert into category_versions (category_id, version, snapshot) values ({lit(cat['id'])}, 1, {jlit(snapshot)})\n"
        f"  on conflict do nothing;\n"
    )


def domain_sql(dom: dict, known: set[str]) -> tuple[str, list[str]]:
    cols = {
        "id": lit(dom["id"]),
        "display_name": jlit(dom["display_name"]),
        "status": lit(dom.get("status", "draft")),
        "count_prompts": alit(dom.get("count_prompts", [])),
        "stakeholder_kinds": alit(dom.get("stakeholder_kinds", [])),
        "action_catalog": alit(dom.get("action_catalog", [])),
        "spatial_layers": alit(dom.get("spatial_layers", [])),
    }
    updates = ", ".join(f"{c} = excluded.{c}" for c in cols if c != "id")
    sql = f"insert into domains ({', '.join(cols)}) values ({', '.join(cols.values())})\n  on conflict (id) do update set {updates};\n"
    missing = []
    for cid in dom.get("categories", []):
        if cid not in known:
            missing.append(cid)
            continue
        sql += f"insert into domain_categories (domain_id, category_id) values ({lit(dom['id'])}, {lit(cid)}) on conflict do nothing;\n"
    return sql, missing


def build() -> str:
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    cats = catalog["categories"]
    known = {c["id"] for c in cats}
    parts = [
        "-- Generated by scripts/sync_catalog.py. Do not edit by hand.\n",
        f"-- catalog version {catalog['version']}\n\n",
    ]
    parts += [category_sql(c) for c in cats]
    parts.append("\n")
    for path in sorted(DOMAINS.glob("*.yaml")):
        sql, missing = domain_sql(yaml.safe_load(path.read_text(encoding="utf-8")), known)
        for cid in missing:
            print(f"warning: {path.name} lists {cid!r}, not in the catalog yet; skipped", file=sys.stderr)
        parts.append(sql + "\n")
    return "".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    sql = build()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != sql:
            print("supabase/seed/catalog.sql is out of date; run scripts/sync_catalog.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(sql, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
